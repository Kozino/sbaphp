  <h2>Our Story</h2>
  <p><strong>From the Compound at Akpu to a Brotherhood for Life.</strong> It began in 2006, when a group of boys entered St. Dominic Savio Seminary, Akpu — in Orumba South Local Government Area, Anambra State — as JSS 1 students. Others joined the same set in the other classes, and so the class that would become one family took shape.</p>
  <p>The seminary gave us more than education. It gave us discipline, faith, and bonds forged in shared study, shared worship and shared labour. When the seminary years ended, the class did not scatter — it organised. The association was founded to keep the brotherhood alive and has been known ever since as the <strong>Savio Bosco Alphas 2012</strong> association. Our name speaks of who we are: the Savio–Bosco family, the Alphas — the first and the beginning — of the class of 2012.</p>
  <p>Today, scattered across parishes, cities and states, we remain what the seminary made us: brothers. We gather for our Annual General Meeting on 31 December every year, we support one another in joy and in sorrow, and we serve the aims written into our constitution.</p>

  <h2>Our Vision</h2>
  <p>To be a model of Christian brotherhood — a united, disciplined and benevolent association whose members live as good citizens of Nigeria and faithful ambassadors of the Church.</p>
  <h2>Our Mission</h2>
  <p>To maintain cordial relationships among members, to give every member an identity, and to support members financially and practically through annual dues, benevolent visits, and the active participation of all.</p>

  <h2>Aims &amp; Objectives</h2>
  <ol>
    <li>To act as a medium through which good and cordial relationships are developed and maintained among members.</li>
    <li>To give identity to, and identify with, every member of the association always.</li>
    <li>To lend helping hands to members, financially and otherwise.</li>
    <li>To encourage the goodwill and active participation of all members.</li>
    <li>To act as a midwife for the all-round development of members as good citizens of Nigeria and ambassadors of the Church.</li>
  </ol>

  <h2>Who Belongs to This Family?</h2>
  <ul>
    <li>Anyone who entered St. Dominic Savio Seminary, Akpu in 2006 as a freshman (JSS 1) and either continued with the set or left the seminary without joining another set.</li>
    <li>Persons who joined the seminary debutants of 2006 thereafter, in the other classes.</li>
    <li>By virtue of association, the spouse of a member, in the case of a marriage valid before the law and the Church.</li>
  </ul>
  <p>Membership may be suspended or terminated by resolution of the management committee, with the member’s right to be heard before the general assembly, or may be resigned in writing to the Secretary.</p>

  <h2>How the Association Is Run</h2>
  <ul>
    <li>A management committee of 3–15 persons, elected for a two-year term, who must be financially up to date before election.</li>
    <li>An Annual General Meeting on 31 December each year, with at least fourteen (14) days’ notice to all members.</li>
    <li>All members are entitled to vote at the AGM by show of hands; the President’s vote breaks a tie.</li>
    <li>A single bank account in the name of the association, signed for by the President, Financial Secretary and Treasurer.</li>
  </ul>
